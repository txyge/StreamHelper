PRAGMA journal_mode = WAL;
CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER PRIMARY KEY, title TEXT NOT NULL, started REAL NOT NULL, ended REAL
);
CREATE UNIQUE INDEX IF NOT EXISTS one_live ON sessions ((1)) WHERE ended IS NULL;
CREATE TABLE IF NOT EXISTS marks (
    id INTEGER PRIMARY KEY, session_id INTEGER NOT NULL REFERENCES sessions,
    seconds INTEGER NOT NULL, label TEXT NOT NULL, note TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
    id INTEGER PRIMARY KEY, session_id INTEGER NOT NULL REFERENCES sessions,
    nick TEXT NOT NULL, body TEXT NOT NULL, rule TEXT, restored INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS questions (
    id INTEGER PRIMARY KEY, session_id INTEGER NOT NULL REFERENCES sessions,
    message_id INTEGER NOT NULL UNIQUE REFERENCES messages,
    nick TEXT NOT NULL, body TEXT NOT NULL, answered INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS rules (
    session_id INTEGER PRIMARY KEY REFERENCES sessions, game TEXT NOT NULL, phrases TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS clips (
    id TEXT PRIMARY KEY, session_id INTEGER NOT NULL REFERENCES sessions,
    start REAL NOT NULL, end REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS recordings (
    id TEXT PRIMARY KEY, session_id INTEGER NOT NULL REFERENCES sessions,
    mime TEXT NOT NULL, duration REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS published (
    id INTEGER PRIMARY KEY CHECK(id = 1), payload TEXT NOT NULL
);
